<?php

namespace Simplydigital\FileUploadManagement\Services;

use InvalidArgumentException;

class FilePathResolver
{
    /**
     * Resolve the directory for an owner.
     *
     * Example:
     *
     *   uploads/Cases/CASE-000123
     *   uploads/Customers/CUST-000456
     */
    public function directory(
        string $ownerType,
        string $ownerIdentifier,
    ): string {
        $ownerType = $this->sanitizeSegment($ownerType);
        $ownerIdentifier = $this->sanitizeSegment($ownerIdentifier);

        $root = trim(
            (string) config('fileupload.root', 'uploads'),
            '/'
        );

        return $this->buildPath(
            $root,
            $ownerType,
            $ownerIdentifier,
        );
    }

    /**
     * Resolve the complete path for a stored file.
     *
     * Example:
     *
     *   uploads/Cases/CASE-000123/01JXYZABC123.pdf
     */
    public function file(
        string $ownerType,
        string $ownerIdentifier,
        string $storedName,
    ): string {
        $directory = $this->directory(
            ownerType: $ownerType,
            ownerIdentifier: $ownerIdentifier,
        );

        $storedName = $this->sanitizeFilename($storedName);

        return $this->buildPath(
            $directory,
            $storedName,
        );
    }

    /**
     * Build a path from individual segments.
     */
    protected function buildPath(string ...$segments): string
    {
        return implode(
            '/',
            array_values(
                array_filter(
                    array_map(
                        static fn (string $segment): string => trim($segment, '/'),
                        $segments
                    ),
                    static fn (string $segment): bool => $segment !== ''
                )
            )
        );
    }

    /**
     * Sanitize a path segment.
     *
     * Prevents directory traversal and removes characters
     * that should not form part of a storage directory.
     */
    protected function sanitizeSegment(string $value): string
    {
        $value = trim($value);

        if ($value === '') {
            throw new InvalidArgumentException(
                'File storage path segments cannot be empty.'
            );
        }

        /*
         * Directory traversal protection.
         */
        if (
            str_contains($value, '..') ||
            str_contains($value, '/') ||
            str_contains($value, '\\')
        ) {
            throw new InvalidArgumentException(
                sprintf(
                    'Invalid file storage path segment: "%s".',
                    $value
                )
            );
        }

        /*
         * Keep letters, numbers, spaces, underscores and hyphens.
         * This works well with identifiers such as:
         *
         * CASE-000123
         * CUST-000456
         */
        $value = preg_replace(
            '/[^A-Za-z0-9_\- ]/',
            '',
            $value
        ) ?? '';

        $value = trim($value);

        if ($value === '') {
            throw new InvalidArgumentException(
                'File storage path segment contains no valid characters.'
            );
        }

        return $value;
    }

    /**
     * Sanitize the generated physical filename.
     *
     * The filename should normally already be generated by
     * the upload service, rather than coming directly from the
     * user's original filename.
     */
    protected function sanitizeFilename(string $filename): string
    {
        $filename = trim($filename);

        if ($filename === '') {
            throw new InvalidArgumentException(
                'Stored filename cannot be empty.'
            );
        }

        if (
            str_contains($filename, '..') ||
            str_contains($filename, '/') ||
            str_contains($filename, '\\')
        ) {
            throw new InvalidArgumentException(
                sprintf(
                    'Invalid stored filename: "%s".',
                    $filename
                )
            );
        }

        $filename = preg_replace(
            '/[^A-Za-z0-9_\-.]/',
            '',
            $filename
        ) ?? '';

        if ($filename === '') {
            throw new InvalidArgumentException(
                'Stored filename contains no valid characters.'
            );
        }

        return $filename;
    }
}